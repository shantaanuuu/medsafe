import 'dart:typed_data';

import 'package:firebase_auth/firebase_auth.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../models/medication_schedule.dart';
import '../models/user_health_profile.dart';
import '../shared_states.dart';

class PdfReportService {
  static final _blue = PdfColor.fromInt(0xFF2563EB);
  static final _navy = PdfColor.fromInt(0xFF111827);
  static final _muted = PdfColor.fromInt(0xFF6B7280);
  static final _red = PdfColor.fromInt(0xFFB91C1C);

  static Future<void> shareDoctorReport({
    required UserHealthProfile profile,
    required List<Medicine> medicines,
    required List<MedicationSchedule> schedules,
  }) async {
    final document = pw.Document(title: 'MedSafe Medical Summary');
    final scheduleByMedicine = {
      for (final schedule in schedules) schedule.cabinetItemId: schedule,
    };
    document.addPage(
      pw.MultiPage(
        pageTheme: pw.PageTheme(
          margin: const pw.EdgeInsets.fromLTRB(32, 32, 32, 36),
          theme: pw.ThemeData.withFont(
            base: pw.Font.helvetica(),
            bold: pw.Font.helveticaBold(),
          ),
        ),
        header: (_) => _reportHeader('Medical Summary for Doctor'),
        footer: (context) => pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              'Generated by MedSafe - for clinical review only',
              style: pw.TextStyle(fontSize: 8, color: _muted),
            ),
            pw.Text(
              'Page ${context.pageNumber} of ${context.pagesCount}',
              style: pw.TextStyle(fontSize: 8, color: _muted),
            ),
          ],
        ),
        build: (_) => [
          pw.SizedBox(height: 14),
          _patientPanel(profile),
          pw.SizedBox(height: 18),
          _section('Clinical alerts', _alerts(profile)),
          pw.SizedBox(height: 18),
          _section(
            'Current medication schedule',
            _medicationTable(medicines, scheduleByMedicine),
          ),
          pw.SizedBox(height: 18),
          _section(
            'Information for the treating clinician',
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                _bullet(
                  "Review this list against the patient's prescription and current clinical status.",
                ),
                _bullet(
                  'Confirm reported allergies before prescribing or administering medication.',
                ),
                _bullet(
                  'Medication start dates shown are cabinet-added dates and may not be the original prescription start date.',
                ),
              ],
            ),
          ),
        ],
      ),
    );
    await _share(
      await document.save(),
      'medsafe_medical_summary_${_safeName(profile.nickname ?? profile.id)}.pdf',
    );
  }

  static Future<void> shareEmergencyCard(Dependent dependent) async {
    final document = pw.Document(title: 'MedSafe Emergency Card');
    document.addPage(
      pw.Page(
        pageTheme: pw.PageTheme(margin: const pw.EdgeInsets.all(32)),
        build: (_) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Container(
              width: double.infinity,
              padding: const pw.EdgeInsets.all(16),
              color: PdfColor.fromInt(0xFFFFE4E6),
              child: pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(
                    'EMERGENCY MEDICAL CARD',
                    style: pw.TextStyle(
                      fontSize: 18,
                      fontWeight: pw.FontWeight.bold,
                      color: _red,
                    ),
                  ),
                  pw.Text(
                    'SHOW AT HOSPITAL',
                    style: pw.TextStyle(
                      fontSize: 9,
                      fontWeight: pw.FontWeight.bold,
                      color: _red,
                    ),
                  ),
                ],
              ),
            ),
            pw.SizedBox(height: 22),
            pw.Text(
              dependent.name.toUpperCase(),
              style: pw.TextStyle(
                fontSize: 25,
                fontWeight: pw.FontWeight.bold,
                color: _navy,
              ),
            ),
            pw.SizedBox(height: 5),
            pw.Text(
              'Age: ${dependent.age} years    |    Weight: ${dependent.weight.toStringAsFixed(1)} kg',
              style: pw.TextStyle(fontSize: 12, color: _muted),
            ),
            pw.SizedBox(height: 22),
            _emergencyBlock(
              'KNOWN ALLERGIES',
              dependent.allergies.isEmpty
                  ? 'None reported'
                  : dependent.allergies.join(', '),
              critical: true,
            ),
            _emergencyBlock(
              'DIAGNOSED CONDITIONS',
              dependent.conditions.isEmpty
                  ? 'None reported'
                  : dependent.conditions.join(', '),
            ),
            _emergencyBlock(
              'ACTIVE MEDICATIONS',
              dependent.adherenceLog.isEmpty
                  ? 'None reported'
                  : dependent.adherenceLog
                        .map(
                          (item) => '${item.medicineName} - ${item.timeString}',
                        )
                        .join('\n'),
            ),
            _emergencyBlock(
              'PRIMARY EMERGENCY CONTACT',
              '${dependent.emergencyContactName}\n${dependent.emergencyContactPhone}',
            ),
            pw.Spacer(),
            pw.Text(
              'This card contains patient-provided information. Verify clinically before treatment.',
              style: pw.TextStyle(fontSize: 8, color: _muted),
            ),
          ],
        ),
      ),
    );
    await _share(
      await document.save(),
      'medsafe_emergency_card_${_safeName(dependent.name)}.pdf',
    );
  }

  static Future<void> _share(Uint8List bytes, String filename) =>
      Printing.sharePdf(bytes: bytes, filename: filename);

  static pw.Widget _reportHeader(String title) => pw.Container(
    padding: const pw.EdgeInsets.only(bottom: 10),
    decoration: pw.BoxDecoration(
      border: pw.Border(
        bottom: pw.BorderSide(color: PdfColor.fromInt(0xFFE5E7EB)),
      ),
    ),
    child: pw.Row(
      children: [
        pw.Container(
          width: 28,
          height: 28,
          alignment: pw.Alignment.center,
          decoration: pw.BoxDecoration(
            color: _blue,
            borderRadius: pw.BorderRadius.circular(7),
          ),
          child: pw.Text(
            'M',
            style: pw.TextStyle(
              color: PdfColors.white,
              fontWeight: pw.FontWeight.bold,
            ),
          ),
        ),
        pw.SizedBox(width: 9),
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              'MedSafe',
              style: pw.TextStyle(
                fontSize: 16,
                fontWeight: pw.FontWeight.bold,
                color: _navy,
              ),
            ),
            pw.Text(title, style: pw.TextStyle(fontSize: 9, color: _muted)),
          ],
        ),
        pw.Spacer(),
        pw.Text(_date(), style: pw.TextStyle(fontSize: 9, color: _muted)),
      ],
    ),
  );

  static pw.Widget _patientPanel(UserHealthProfile profile) => pw.Container(
    padding: const pw.EdgeInsets.all(16),
    decoration: pw.BoxDecoration(
      color: PdfColor.fromInt(0xFFEFF6FF),
      borderRadius: pw.BorderRadius.circular(8),
    ),
    child: pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          _displayName(profile),
          style: pw.TextStyle(
            fontSize: 21,
            fontWeight: pw.FontWeight.bold,
            color: _navy,
          ),
        ),
        pw.SizedBox(height: 10),
        pw.Row(
          children: [
            _detail('Age', profile.age?.toString() ?? 'Not recorded'),
            _detail('Sex', profile.sex ?? 'Not recorded'),
            _detail(
              'Weight',
              profile.weightKg == null
                  ? 'Not recorded'
                  : '${profile.weightKg} kg',
            ),
            _detail('Profile', profile.role),
          ],
        ),
      ],
    ),
  );

  static pw.Widget _detail(String label, String value) => pw.Expanded(
    child: pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          label.toUpperCase(),
          style: pw.TextStyle(fontSize: 7, color: _muted),
        ),
        pw.SizedBox(height: 3),
        pw.Text(
          value,
          style: pw.TextStyle(
            fontSize: 10,
            fontWeight: pw.FontWeight.bold,
            color: _navy,
          ),
        ),
      ],
    ),
  );
  static pw.Widget _section(String title, pw.Widget body) => pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: [
      pw.Text(
        title,
        style: pw.TextStyle(
          fontSize: 14,
          fontWeight: pw.FontWeight.bold,
          color: _navy,
        ),
      ),
      pw.SizedBox(height: 8),
      body,
    ],
  );
  static pw.Widget _alerts(UserHealthProfile profile) => pw.Table(
    border: pw.TableBorder.all(color: PdfColor.fromInt(0xFFE5E7EB)),
    columnWidths: const {0: pw.FlexColumnWidth(1), 1: pw.FlexColumnWidth(3)},
    children: [
      _alertRow(
        'Known allergies',
        profile.allergies.isEmpty
            ? 'None reported'
            : profile.allergies.join(', '),
        true,
      ),
      _alertRow(
        'Chronic conditions',
        profile.chronicConditions.isEmpty
            ? 'None reported'
            : profile.chronicConditions.join(', '),
        false,
      ),
    ],
  );
  static pw.TableRow _alertRow(String label, String value, bool critical) =>
      pw.TableRow(
        children: [
          pw.Padding(
            padding: const pw.EdgeInsets.all(8),
            child: pw.Text(
              label,
              style: pw.TextStyle(
                fontSize: 10,
                fontWeight: pw.FontWeight.bold,
                color: critical ? _red : _navy,
              ),
            ),
          ),
          pw.Padding(
            padding: const pw.EdgeInsets.all(8),
            child: pw.Text(
              value,
              style: pw.TextStyle(fontSize: 10, color: critical ? _red : _navy),
            ),
          ),
        ],
      );
  static pw.Widget _medicationTable(
    List<Medicine> medicines,
    Map<String, MedicationSchedule> schedules,
  ) {
    final headers = [
      'Medicine',
      'Generic / form',
      'Schedule',
      'Added / start',
      'Quantity',
    ];
    final rows = medicines.map((med) {
      final schedule = schedules[med.id];
      final scheduleText = schedule == null
          ? 'Not scheduled'
          : '${schedule.frequencyPerDay}x daily\n${schedule.scheduledTimes.join(', ')}';
      return [
        med.name,
        [
          med.genericName,
          med.dosageForm,
        ].where((item) => item.isNotEmpty).join(' / '),
        scheduleText,
        _formatDate(med.addedDate),
        med.quantity?.toString() ?? 'Not recorded',
      ];
    }).toList();
    if (rows.isEmpty)
      return pw.Text(
        'No medicines are currently listed in the cabinet.',
        style: pw.TextStyle(fontSize: 10, color: _muted),
      );
    return pw.TableHelper.fromTextArray(
      headers: headers,
      data: rows,
      headerStyle: pw.TextStyle(
        fontSize: 8,
        fontWeight: pw.FontWeight.bold,
        color: PdfColors.white,
      ),
      headerDecoration: pw.BoxDecoration(color: _blue),
      cellStyle: pw.TextStyle(fontSize: 8, color: _navy),
      cellPadding: const pw.EdgeInsets.all(6),
      border: pw.TableBorder.all(color: PdfColor.fromInt(0xFFE5E7EB)),
      columnWidths: {
        0: const pw.FlexColumnWidth(1.3),
        1: const pw.FlexColumnWidth(1.5),
        2: const pw.FlexColumnWidth(1.3),
        3: const pw.FlexColumnWidth(1),
        4: const pw.FlexColumnWidth(.7),
      },
    );
  }

  static pw.Widget _emergencyBlock(
    String heading,
    String text, {
    bool critical = false,
  }) => pw.Container(
    width: double.infinity,
    margin: const pw.EdgeInsets.only(bottom: 13),
    padding: const pw.EdgeInsets.all(12),
    decoration: pw.BoxDecoration(
      border: pw.Border.all(
        color: critical
            ? PdfColor.fromInt(0xFFFCA5A5)
            : PdfColor.fromInt(0xFFE5E7EB),
      ),
      borderRadius: pw.BorderRadius.circular(6),
      color: critical ? PdfColor.fromInt(0xFFFFF1F2) : PdfColors.white,
    ),
    child: pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          heading,
          style: pw.TextStyle(
            fontSize: 9,
            color: critical ? _red : _muted,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
        pw.SizedBox(height: 5),
        pw.Text(
          text,
          style: pw.TextStyle(
            fontSize: 13,
            color: critical ? _red : _navy,
            fontWeight: pw.FontWeight.bold,
          ),
        ),
      ],
    ),
  );
  static String _displayName(UserHealthProfile profile) {
    final nickname = profile.nickname?.trim();
    if (nickname != null && nickname.isNotEmpty) return nickname;
    final firebaseName = FirebaseAuth.instance.currentUser?.displayName?.trim();
    if (firebaseName != null && firebaseName.isNotEmpty) return firebaseName;
    final email = FirebaseAuth.instance.currentUser?.email;
    if (email != null && email.contains('@')) return email.split('@').first;
    return 'Patient';
  }

  static pw.Widget _bullet(String text) => pw.Padding(
    padding: const pw.EdgeInsets.only(bottom: 5),
    child: pw.Text('- $text', style: pw.TextStyle(fontSize: 10, color: _navy)),
  );
  static String _date() {
    final now = DateTime.now();
    return '${now.day.toString().padLeft(2, '0')}/${now.month.toString().padLeft(2, '0')}/${now.year}';
  }

  static String _formatDate(DateTime value) =>
      '${value.day.toString().padLeft(2, '0')}/${value.month.toString().padLeft(2, '0')}/${value.year}';
  static String _safeName(String name) => name
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
      .replaceAll(RegExp(r'^_|_$'), '');
}
